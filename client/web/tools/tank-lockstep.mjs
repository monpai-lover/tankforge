// Writes the lockstep fixture for crates/physics/src/tank: the JS mirror of the tank model driven
// through a few seconds of waves, turning and braking; the Rust test replays the same inputs and
// must land on the same states.   node tools/tank-lockstep.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { rig, ground, run, placeTank } from '../test/tankrig.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '../../../crates/physics/src/tank/lockstep.json');
const wave = (x, z) => (z > 4 && z < 40 ? 0.1 * (1 - Math.cos(((z - 4) / 5) * 2 * Math.PI)) : 0) + 0.03 * Math.sin(x * 0.9);
const g = ground(wave, 'dirt');
const cases = [];
for (const id of ['su_t34_85', 'us_m4a3_76w_hvss']) {
  const r = rig(id);
  placeTank(r.tm, r.t, g, 0, 0, 0.2);
  const plan = [
    [1.5, { throttle: 0.7, steer: 0, brake: 0 }],
    [1.0, { throttle: 0.7, steer: 0.5, brake: 0 }],
    [0.5, { throttle: 0, steer: 0, brake: 1 }],
  ];
  const snaps = [];
  for (const [secs, input] of plan) {
    run(r, g, input, secs, 1 / 120);
    const b = r.t.body;
    snaps.push({ origin: b.origin(), ez: b.ez.slice(), ey: b.ey.slice(), comp: r.t.ss.comp.slice(), belts: [r.t.ds.belts[-1].v, r.t.ds.belts[1].v], gear: r.t.ds.gear });
  }
  cases.push({ id, plan: plan.map(([secs, i]) => ({ secs, ...i })), snaps });
}
fs.writeFileSync(out, JSON.stringify({ note: 'generated by client/web/tools/tank-lockstep.mjs', cases }, null, 1) + '\n');
console.log('wrote', out);
